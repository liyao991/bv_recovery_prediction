# test_readFasta_id.R - reproduce assignTaxonomy reference parsing (all-ASCII)
suppressWarnings(Sys.setlocale("LC_CTYPE", "Chinese (Simplified)_China.936"))
suppressPackageStartupMessages({ library(ShortRead) })
refFasta <- "<DATA_DIR>/silva/silva_138.1_train_set_bac_arch.fa.gz"
cat("calling readFasta ...\n")
refsr <- tryCatch(readFasta(refFasta), error = function(e) { cat("READ ERROR:", conditionMessage(e), "\n"); NULL })
if (is.null(refsr)) quit(status = 1)
cat("read ok, n =", length(refsr), "\n")
idv <- as.character(id(refsr))
cat("first 5 id values:\n")
print(head(idv, 5))
cat("id contains ';' ?", grepl(";", idv[1]), "\n")
cat("nchar of first id:", nchar(idv[1]), "\n")
cat("== TEST_DONE ==\n")
